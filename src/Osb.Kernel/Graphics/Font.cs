    public static byte* Glyph(int c)
    {
        int i = c & 0xFF;
        if (i >= 128) i = 0;
        return _fontData + i * GlyphBytes;
    }

    // Returns the 8 bytes for character c by copying from the inline table.
    // Avoids any pointer-lifetime issues with fixed buffers in NativeAOT.
    public static void GetGlyph(int c, byte* dst)
    {
        int i = c & 0xFF;
        if (i >= 128) i = 0;
        for (int r = 0; r < 8; r++)
            dst[r] = _fontBytes[i * 8 + r];
    }

    public static void DrawChar(int x, int y, char ch, byte fg, byte bg)
    {
        byte* g = stackalloc byte[8];
        GetGlyph((int)ch, g);
        for (int r = 0; r < GlyphHeight; r++)
        {
            int py = y + r;
            if (py < 0 || py >= Gfx.Height) continue;
            byte bits = g[r];
            // Clear the full row to background, then draw the set bits as
            // horizontal runs. FillRect is reliable; per-pixel SetPixel is
            // not under NativeAOT here.
            Gfx.FillRect(x, py, GlyphWidth, 1, bg);
            for (int c = 0; c < GlyphWidth; c++)
            {
                if ((bits & (1 << c)) != 0)
                    Gfx.SetPixel(x + c, py, fg);
            }
        }
    }

    public static int DrawString(int x, int y, string s, byte fg, byte bg)
    {
        fixed (char* p = s)
        {
            for (int i = 0; i < s.Length; i++)
                DrawChar(x + i * GlyphWidth, y, p[i], fg, bg);
        }
        return x + s.Length * GlyphWidth;
    }

    public static int DrawString(int x, int y, char* s, int len, byte fg, byte bg)
    {
        for (int i = 0; i < len; i++)
            DrawChar(x + i * GlyphWidth, y, s[i], fg, bg);
        return x + len * GlyphWidth;
    }

    public static int StringWidth(int len) { return len * GlyphWidth; }
